from __future__ import annotations

from pathlib import Path
from typing import List

import numpy as np

from .chs import COMPONENTS, ComponentHealthScorer
from .features import FEATURE_NAMES, N_FEATURES
from .pqdna import PQDNAAggregator
from .rul import RULEstimator


def _q15(x: np.ndarray) -> np.ndarray:
    return np.clip(np.round(x * 32768.0), -32768, 32767).astype(np.int16)


def _q23(x: np.ndarray) -> np.ndarray:
    # 24-bit fixed for slightly larger ranges (RUL coefficients).
    return np.clip(np.round(x * 8388608.0), -8388608, 8388607).astype(np.int32)


def export_c_header(
    out_path: str,
    aggregator: PQDNAAggregator,
    chs: ComponentHealthScorer,
    rul: RULEstimator,
) -> Path:
    """Emit a self-contained `pqdna_model.h` with all model constants."""
    lines: List[str] = []
    lines.append("/* Auto-generated by pqdna.edge_export. Do not edit by hand. */")
    lines.append("#ifndef PQDNA_MODEL_H")
    lines.append("#define PQDNA_MODEL_H")
    lines.append("#include <stdint.h>")
    lines.append(f"#define PQDNA_N_FEATURES {N_FEATURES}")
    lines.append(f"#define PQDNA_N_COMPONENTS {len(COMPONENTS)}")
    lines.append(f"#define PQDNA_CHS_N_INPUTS {int(chs.W.shape[1])}")
    lines.append(f"#define PQDNA_CHS_USE_AGE {1 if chs.use_age else 0}")

    # Feature names (for diagnostics; could be stripped in release).
    lines.append("static const char *PQDNA_FEATURE_NAMES[PQDNA_N_FEATURES] = {")
    for name in FEATURE_NAMES:
        lines.append(f"    \"{name}\",")
    lines.append("};")

    lines.append("static const char *PQDNA_COMPONENT_NAMES[PQDNA_N_COMPONENTS] = {")
    for c in COMPONENTS:
        lines.append(f"    \"{c}\",")
    lines.append("};")

    # alpha (Q15 in [0,1)).
    alpha_q = _q15(aggregator.alpha)
    lines.append("static const int16_t PQDNA_ALPHA_Q15[PQDNA_N_FEATURES] = {")
    lines.append("    " + ", ".join(str(int(v)) for v in alpha_q))
    lines.append("};")

    # CHS weight matrix (Q15).
    W_q = _q15(chs.W)
    lines.append(
        "static const int16_t PQDNA_CHS_W_Q15[PQDNA_N_COMPONENTS][PQDNA_CHS_N_INPUTS] = {"
    )
    for row in W_q:
        lines.append("    {" + ", ".join(str(int(v)) for v in row) + "},")
    lines.append("};")

    bias_q = _q15(chs.bias)
    lines.append("static const int16_t PQDNA_CHS_BIAS_Q15[PQDNA_N_COMPONENTS] = {")
    lines.append("    " + ", ".join(str(int(v)) for v in bias_q))
    lines.append("};")
    lines.append(f"static const float PQDNA_CHS_SCALE = {chs.scale:.6g}f;")

    # Ridge RUL coefficients.
    if rul.model == "ridge" and rul.coefs_ is not None:
        coefs_q = _q23(rul.coefs_ / max(1.0, float(np.max(np.abs(rul.coefs_))) + 1e-9))
        lines.append(
            f"#define PQDNA_RUL_INPUT_LEN {len(rul.coefs_)}"
        )
        lines.append("static const int32_t PQDNA_RUL_COEFS_Q23[PQDNA_RUL_INPUT_LEN] = {")
        lines.append("    " + ", ".join(str(int(v)) for v in coefs_q))
        lines.append("};")
        lines.append(
            f"static const float PQDNA_RUL_SCALE = {float(np.max(np.abs(rul.coefs_)) + 1e-9):.6g}f;"
        )

    lines.append("#endif /* PQDNA_MODEL_H */")
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines), encoding="utf-8")
    return p


def memory_footprint_bytes(aggregator: PQDNAAggregator,
                           chs: ComponentHealthScorer,
                           rul: RULEstimator) -> dict:
    """Return the on-device constant + state footprint, in bytes."""
    n_feat = N_FEATURES
    n_comp = len(COMPONENTS)
    foot = {
        "S_state_bytes": n_feat * 2,                              # int16 Q15
        "alpha_bytes": n_feat * 2,
        "age_counter_bytes": 4 if chs.use_age else 0,             # uint32 run-days
        "chs_W_bytes": int(chs.W.size) * 2,
        "chs_bias_bytes": n_comp * 2,
    }
    if rul.model == "ridge" and rul.coefs_ is not None:
        foot["rul_coefs_bytes"] = int(len(rul.coefs_) * 4)        # int32 Q23
    foot["total_bytes"] = int(sum(foot.values()))
    return foot
