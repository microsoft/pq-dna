"""Fixed-point export of the PQ-DNA state, alpha vector, CHS weights and
ridge-RUL coefficients to a C header that a meter firmware build can include.

This demonstrates that the entire trained model fits in a few hundred bytes of
flash on a Cortex-M-class part.
"""

